export interface FieldDef {
    /**
     *
     */
    label: Record<string, string>;
    /**
     *
     */
    type: 'boolean' | 'number' | 'string';
    /**
     *
     */
    unit?: string;
    /**
     *
     */
    writeTopic?: string; // 'control' | 'mode' | 'fan' | 'econo' | 'powerful' | 'comfort' |
    // 'streamer' | 'led' | 'quiet' | 'humidify' | 'demand' |
    // 'autoe' | 'autop' | 'restart' |
    // 'setting:autot' | 'setting:autor' | 'setting'
    /**
     *
     */
    writeOnly?: boolean;
    /**
     * When true: state is user-writable (read: true, write: true) even without a writeTopic.
     * Used for config states that are forwarded to the device via MQTT setting topics.
     */
    forceWrite?: boolean;
    /**
     *
     */
    bleKey?: boolean;
    /**
     *
     */
    role?: string;
    /**
     *
     */
    states?: Record<string, string>;
    /**
     *
     */
    min?: number;
    /**
     *
     */
    max?: number;
}

